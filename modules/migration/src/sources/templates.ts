/** The sample pack as CSV uploads. `override` replaces tables (tests: a changed export). */
export function sampleGuesthouseFiles(
  bd: LocalDate,
  override: Record<string, string[][]> = {},
): UploadedFile[] {
  const pack = { ...sampleGuesthousePack(bd), ...override };
  return Object.entries(pack).map(([name, rows]) => ({
    name: `${name}.csv`,
    content: toCsv(TEMPLATE_HEADERS[name] as string[], rows),
  }));
}

/** The sample pack as one Excel workbook (base64 upload). */
export function sampleGuesthouseWorkbook(bd: LocalDate): UploadedFile {
  const pack = sampleGuesthousePack(bd);
  return {
    name: 'coral-nest-migration.xlsx',
    encoding: 'base64',
    content: writeXlsx(
      Object.entries(pack).map(([name, rows]) => ({
        name,
        headers: TEMPLATE_HEADERS[name] as string[],
        rows,
      })),
    ).toString('base64'),
  };
}


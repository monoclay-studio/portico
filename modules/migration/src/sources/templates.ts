/** Empty templates (CSV text per table) to download. */
export function templateFiles(): UploadedFile[] {
  return Object.entries(TEMPLATE_HEADERS).map(([name, headers]) => ({
    name: `${name}.csv`,
    content: toCsv(headers, []),
  }));
}

/** The same templates as one Excel workbook (base64). */
export function templateWorkbook(): string {
  return writeXlsx(
    Object.entries(TEMPLATE_HEADERS).map(([name, headers]) => ({ name, headers, rows: [] })),
  ).toString('base64');
}

